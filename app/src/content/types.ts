// Types for the content bundle produced by scripts/build_content.py.
// Mirrors schema/content.schema.json (see docs/CONTENT_FORMAT.md).

export type Flag = 'soft' | 'nosoft' | 'drop' | 'front' | 'compound' | 'double' | 'irr' | 'nodrill' | 'aorist_ir';

export interface Word {
  id: string;
  lemma: string;
  pos: string;
  gloss: string[];
  flags?: Flag[];
  forms?: Record<string, string>;
  /** Verbs: the stem suffixes attach to, when it isn't the infinitive minus -mAk. */
  stem?: string;
  images?: string[];
  audio?: string;
  notes?: string;
}

export interface Sentence {
  id: string;
  tr: string;
  en: string[];
  words: string[];
  grammar: string[];
  audio?: string;
  native_required?: boolean;
  phrase?: boolean;
}

export interface Suffix {
  id: string;
  form: string;
  gloss: string;
  slot?: string;
  introduced_by: string;
}

export interface Pattern {
  id: string;
  description: string;
  suffix?: string;
  /** A chain of suffixes, e.g. [sfx.loc, sfx.cop_1sg] (instead of `suffix`). */
  suffixes?: string[];
  word_filter?: Record<string, unknown>;
}

export interface GrammarPoint {
  id: string;
  title: string;
  suffixes?: string[];
  reference: string;
  patterns?: Pattern[];
  feedback?: Record<string, string>;
}

export interface Card {
  kind: 'hook' | 'rule' | 'examples' | 'note' | 'summary';
  title?: string;
  body: string;
  audio?: string[];
  images?: string[];
  sentences?: string[];
  interactive?: { component: string; params?: Record<string, unknown> };
}

export interface DialogueTurn {
  speaker: 'A' | 'B';
  sentence?: string;
  blank?: true;
  answers?: string[];
  /** Spoken variants for the blank (see Item.spoken). */
  spoken?: string[];
}

export interface Item {
  id: string;
  type:
    | 'pick_suffix' | 'type_form' | 'build_word' | 'translate_to_tr' | 'translate_to_en'
    | 'listen_choose' | 'dictation' | 'spot_error' | 'picture_choose' | 'qa'
    | 'mini_dialogue' | 'contrast_pair'
    // generated by the review builder only (not authored in content):
    | 'meaning_choice' | 'word_recall';
  grammar: string[];
  pattern?: string;
  feedback?: string | Record<string, string>;
  note?: string;
  /** English shown after answering, when the automatic one isn't right (items with pictures). */
  translation?: string;
  images?: string[];
  audio?: string[];
  base?: string;
  suffix?: string;
  suffixes?: string[];
  prompt?: string;
  options?: string[];
  answer?: string;
  answers?: string[];
  /** Spoken / informal variants (answer patterns): graded "almost" with an "in writing" note, never model answers. */
  spoken?: string[];
  tiles?: string[];
  sentence?: string;
  word_bank?: string[];
  typed?: boolean;
  text?: string;
  error?: string;
  question?: string;
  turns?: DialogueTurn[];
}

export interface Lesson {
  id: string;
  title: string;
  grammar: string;
  new_words?: string[];
  sessions: {
    learn: { minutes?: number; cards: Card[]; items: Item[] };
    practise: { minutes?: number; items: Item[]; talk?: Talk };
  };
}

export type TalkKind =
  | 'sounds' | 'point_and_name' | 'introduce' | 'interview' | 'guess' | 'correct_me' | 'hide_and_find'
  | 'act_it' | 'roleplay' | 'plan' | 'tell' | 'listen_report' | 'free_chat';

/** Talk task: a short conversation with a Turkish speaker after Practise (docs/TALK_TASKS.md §5). */
export interface Talk {
  id: string; // <lesson or checkpoint>.talk
  kind: TalkKind;
  minutes: number;
  title: string;
  how: string[];
  /** Sentence IDs the learner prepares (audio + English). */
  phrases: string[];
  goals: string[];
  partner: { topic: string; knows: string; questions: string[] };
  requires?: 'survival'[];
}

/** The fixed Turkish frame of the partner card (content/talk/partner_frame.yaml). */
export interface PartnerFrame {
  greeting: string;
  intro: string;
  rules: string[];
  topic_label: string;
  knows_label: string;
  questions_label: string;
  closing: string;
  /** The learner's "If you're stuck" sentence IDs. */
  survival: string[];
}

/** How a composite image arranges its parts (first item = the object, second = where it is). */
export interface Compose {
  layout: 'on_top' | 'in' | 'at' | 'row' | 'panels';
  items: (string | Compose)[];
}

export interface Asset {
  id: string;
  kind: 'image' | 'audio';
  file?: string;
  source: string;
  license: string;
  status: 'planned' | 'ready';
  derived_from?: string[];
  compose?: Compose;
  text?: string;
  notes?: string;
}

export interface Course {
  units: { id: string; title: string; lessons: string[]; checkpoint?: string }[];
  lessons: Record<string, { title: string; grammar: string; file?: string }>;
}

/** End-of-unit checkpoint (content/checkpoints/C<n>.yaml). */
export interface Checkpoint {
  id: string;
  unit: string;
  title: string;
  minutes?: number;
  /** Score needed to pass (default 0.7). */
  pass?: number;
  intro: Card;
  items: Item[];
  talk?: Talk;
}

export interface Bundle {
  version: number;
  course: Course;
  grammar: Record<string, GrammarPoint>;
  lessons: Record<string, Lesson>;
  checkpoints: Record<string, Checkpoint>;
  packs: Record<string, unknown>;
  lexicon: Record<string, Word>;
  sentences: Record<string, Sentence>;
  suffixes: Record<string, Suffix>;
  morphTests: { word: string; suffixes: string[]; expected: string; note?: string }[];
  assets: Record<string, Asset>;
  talkFrame: PartnerFrame;
}
